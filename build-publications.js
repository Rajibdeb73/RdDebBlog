#!/usr/bin/env node
/*
 * build-publications.js — CivicLens dashboard manifest generator
 * ---------------------------------------------------------------
 * Scans every *.html report in this folder, reads its <meta name="pub:*">
 * tags, and writes publications.js + publications.json, sorted newest first.
 *
 * The index.html dashboard loads publications.js and renders the nav tabs,
 * card grid and jump list from it — so publishing a new report is just:
 *   1. drop a new *.html file with pub: meta tags in the folder
 *   2. push (the GitHub Action runs this script and commits the manifest)
 *
 * Run locally anytime with:  node build-publications.js
 *
 * No dependencies — plain Node.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const DIR = __dirname;
// Files that are NOT publications (the dashboard shell + archives).
const EXCLUDE = new Set(['index.html', 'index0.html']);

/** Pull the content of <meta name="pub:KEY" content="VALUE"> (either attr order). */
function meta(html, key) {
  const k = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const patterns = [
    new RegExp(`<meta[^>]*name=["']pub:${k}["'][^>]*content=["']([^"']*)["']`, 'i'),
    new RegExp(`<meta[^>]*content=["']([^"']*)["'][^>]*name=["']pub:${k}["']`, 'i'),
  ];
  for (const re of patterns) {
    const m = html.match(re);
    if (m) return decodeEntities(m[1].trim());
  }
  return '';
}

function decodeEntities(s) {
  return s
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'");
}

function title(html) {
  const m = html.match(/<title>([^<]*)<\/title>/i);
  return m ? decodeEntities(m[1].trim()) : '';
}

/** Git's last-commit date (YYYY-MM-DD) for a file, or '' if git is unavailable. */
function gitDate(file) {
  try {
    return execSync(`git log -1 --format=%cs -- "${file}"`, {
      cwd: DIR,
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .toString()
      .trim();
  } catch {
    return '';
  }
}

function build() {
  const files = fs
    .readdirSync(DIR)
    .filter((f) => f.toLowerCase().endsWith('.html') && !EXCLUDE.has(f));

  const pubs = [];
  const skipped = [];

  for (const file of files) {
    const html = fs.readFileSync(path.join(DIR, file), 'utf8');
    // A file is treated as a publication only if it opts in with pub: meta.
    // (Prevents stray/experimental HTML from leaking onto the dashboard.)
    const hasMeta = /name=["']pub:(title|date)["']/i.test(html);
    if (!hasMeta) {
      skipped.push(file);
      continue;
    }

    const t = meta(html, 'title') || title(html) || file.replace(/\.html$/i, '');
    const date = meta(html, 'date') || gitDate(file) || '';

    pubs.push({
      file,
      title: t,
      nav: meta(html, 'nav') || t,
      date,
      desc: meta(html, 'desc'),
      category: meta(html, 'category'),
      tags: meta(html, 'tags')
        ? meta(html, 'tags').split(',').map((s) => s.trim()).filter(Boolean)
        : [],
      icon: meta(html, 'icon') || '📄',
      accent: meta(html, 'accent') || '#364F64',
      accent2: meta(html, 'accent2') || meta(html, 'accent') || '#607D90',
      metric: meta(html, 'metric'),
      metricLabel: meta(html, 'metricLabel'),
      badge: meta(html, 'badge') || 'Live',
    });
  }

  // Newest first; undated entries sink to the bottom (still alphabetised).
  pubs.sort((a, b) => {
    if (a.date && b.date) return b.date.localeCompare(a.date);
    if (a.date) return -1;
    if (b.date) return 1;
    return a.title.localeCompare(b.title);
  });

  const json = JSON.stringify(pubs, null, 2);
  fs.writeFileSync(path.join(DIR, 'publications.json'), json + '\n');
  fs.writeFileSync(
    path.join(DIR, 'publications.js'),
    '/* AUTO-GENERATED by build-publications.js — do not edit by hand. */\n' +
      'window.PUBLICATIONS = ' +
      json +
      ';\n'
  );

  console.log(`Wrote ${pubs.length} publication(s):`);
  for (const p of pubs) console.log(`  ${p.date || '（no date）'}  ${p.file}`);
  if (skipped.length) {
    console.log(`\nSkipped ${skipped.length} HTML file(s) without pub: meta tags:`);
    for (const f of skipped) console.log(`  ${f}`);
  }
}

build();
